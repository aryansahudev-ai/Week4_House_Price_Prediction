import streamlit as st
import pandas as pd
import joblib

# Load trained model and scaler
model = joblib.load("house_price_model.pkl")
scaler = joblib.load("house_price_scaler.pkl")

# Feature order used by StandardScaler during training
scaler_columns = [
    "Square_Footage",
    "Num_Bedrooms",
    "Num_Bathrooms",
    "Year_Built",
    "Garage_Size",
    "Lot_Size",
    "Neighborhood_Quality"
]

# Feature order used by Linear Regression
model_columns = [
    "Square_Footage",
    "Num_Bedrooms",
    "Year_Built",
    "Garage_Size",
    "Lot_Size",
    "Num_Bathrooms",
    "Neighborhood_Quality"
]

st.set_page_config(
    page_title="House Price Predictor",
    page_icon="🏠",
    layout="centered"
)

st.title("🏠 House Price Predictor")
st.write(
    "Predict house prices using your trained "
    "Linear Regression model."
)

st.subheader("Enter House Details")

with st.form("house_details"):
    square_footage = st.number_input(
        "Square Footage",
        min_value=503,
        max_value=4999,
        value=1500
    )

    bedrooms = st.selectbox(
        "Number of Bedrooms", [1, 2, 3, 4, 5], index=2
    )

    bathrooms = st.selectbox(
        "Number of Bathrooms", [1, 2, 3], index=1
    )

    year_built = st.number_input(
        "Year Built",
        min_value=1950,
        max_value=2022,
        value=2000
    )

    garage_size = st.selectbox(
        "Garage Size", [0, 1, 2], index=1
    )

    lot_size = st.number_input(
        "Lot Size",
        min_value=0.506,
        max_value=4.989,
        value=2.5,
        step=0.1
    )

    neighborhood_quality = st.slider(
        "Neighborhood Quality",
        min_value=1,
        max_value=10,
        value=5
    )

    submitted = st.form_submit_button(
        "Predict House Price",
        type="primary",
        use_container_width=True
    )

if submitted:
    # Arrange values in the scaler's original column order
    input_data = pd.DataFrame([{
        "Square_Footage": square_footage,
        "Num_Bedrooms": bedrooms,
        "Num_Bathrooms": bathrooms,
        "Year_Built": year_built,
        "Garage_Size": garage_size,
        "Lot_Size": lot_size,
        "Neighborhood_Quality": neighborhood_quality
    }], columns=scaler_columns)

    # Apply the previously fitted scaler
    scaled_values = scaler.transform(input_data)

    scaled_data = pd.DataFrame(
        scaled_values,
        columns=scaler_columns
    )

    # Match the exact order used when training the model
    scaled_data = scaled_data[model_columns]

    prediction = model.predict(scaled_data)[0]

    st.divider()
    st.subheader("Estimated House Price")

    st.metric(
        label="Predicted Price",
        value=f"{prediction:,.2f}"
    )

    st.caption(
        "This estimate is generated by your trained model. "
        "It is not a guaranteed selling price."
    )
